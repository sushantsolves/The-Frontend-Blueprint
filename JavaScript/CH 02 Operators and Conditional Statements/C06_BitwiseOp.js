// ============================================================
// 5. BITWISE OPERATORS
// ============================================================

// Definition:
// Perform operations on the binary (32-bit integer) representation
// of numbers in JavaScript.

// &   Bitwise AND
// |   Bitwise OR
// ^   Bitwise XOR (true when corresponding bits differ)
// ~   Bitwise NOT (inverts bits)
// <<  Left shift
// >>  Signed right shift (preserves the sign)
// >>> Unsigned right shift (fills left bits with zeros)

console.log(5 & 3);   // 1
console.log(5 | 3);   // 7
console.log(5 ^ 3);   // 6
console.log(~5);      // -6
console.log(5 << 1);  // 10
console.log(5 >> 1);  // 2
console.log(5 >>> 1); // 2
