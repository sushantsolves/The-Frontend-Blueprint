// Definition:
// The + operator concatenates (joins) strings when string
// concatenation applies. The += operator can append to a string.

let firstName = "Sushant";
let lastName = "Raj";

console.log(firstName + " " + lastName); // Sushant Raj

firstName += " Raj";
console.log(firstName); // Sushant Raj
