// ============================================================
// 7. CONDITIONAL / TERNARY OPERATOR
// ============================================================

// Definition:
// A shorthand for choosing one of two expressions based on
// a condition.

// Syntax:
// condition ? expressionIfTrue : expressionIfFalse;

let marks = 75;

let result = marks >= 40 ? "Pass" : "Fail";

console.log(result); // Pass
